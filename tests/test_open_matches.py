"""T39: with `open_matches_scope: "all_open"` every scan rewrites output/open_matches.csv from all of data/jobs.db (no network).

Since T124 the default is the jobs the last scan scored (tests/test_open_matches_this_run.py); these tests set the rolling list."""
import csv
import sqlite3
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

import pytest

from job_hunt import scanner, tracker
from job_hunt.db import init_db, save_job, update_job_status
from job_hunt.models import JobPosting, job_key

DEFAULT_WINDOW = object()      # the config names no window at all
TODAY = date.today()


def _job(name, posted=""):
    return JobPosting(global_id=f"gh:x:{name}", ats="greenhouse", company="X", title=f"Backend Engineer {name}",
                      location="Bengaluru, India", is_remote=False, url=f"https://x/{name}", description_text="Node.js",
                      posted_at=posted)


def _score_earlier(job, score, days_ago):
    """A job scored on an earlier scan, `days_ago` days back."""
    save_job(job)
    update_job_status(job_key(job), "scored", score, "r")
    con = sqlite3.connect("data/jobs.db")
    when = (datetime.now(timezone.utc) - timedelta(days=days_ago)).isoformat()
    con.execute("UPDATE jobs SET scored_at = ? WHERE global_id = ?", (when, job.global_id))
    con.commit()
    con.close()


@pytest.fixture
def env(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(scanner, "send_telegram", lambda *a, **k: False)
    (tmp_path / "resume.md").write_text("Node.js")
    init_db("data/jobs.db")
    iso = lambda d: (TODAY - timedelta(days=d)).isoformat()   # noqa: E731
    _score_earlier(_job("A", iso(2)), 80, 2)                   # applied → never listed
    _score_earlier(_job("B", iso(3)), 75, 3)
    _score_earlier(_job("C", iso(1)), 50, 1)                   # below min_score
    _score_earlier(_job("D", iso(40)), 90, 1)                  # posted 40 days ago
    _score_earlier(_job("E", "Posted 5 Days Ago"), 85, 30)     # Workday text, fetched 30 days ago: 35 days old now
    _score_earlier(_job("F", ""), 65, 4)                       # undated: kept, like the scan's own window
    tracker.mark_job("https://x/A", "applied")

    def run(window=None, new=()):
        monkeypatch.setattr(scanner, "fetch_company_jobs", lambda c: list(new))

        def fake_score(job, **kw):
            update_job_status(job_key(job), "scored", 70, "r")
            return {"score": 70, "reason": "r", "status": "scored"}

        monkeypatch.setattr(scanner, "score_and_process_job", fake_score)
        cand = {"resume_path": "resume.md", "min_score": 60}
        if window is not DEFAULT_WINDOW:       # window=None is JSON null: no window (T02: 7 days unless the config says so)
            cand["max_posted_age_days"] = window
        scanner.run_scan({"candidate": cand, "gemini_api_key": "k", "telegram": {}, "open_matches_scope": "all_open"},   # T124: the rolling list of T39
                         [{"name": "X", "ats": "greenhouse", "slug": "x"}])
        return [r["Application URL"].rsplit("/", 1)[1] for r in
                csv.DictReader(Path("output/open_matches.csv").open(encoding="utf-8"))]
    return run


def test_open_matches_lists_unapplied_jobs_above_min_score_inside_the_window(env):
    """The done-when: regenerated by a scan, applied jobs excluded."""
    assert env(window=30, new=[_job("G", TODAY.isoformat())]) == ["B", "G", "F"]


def test_without_a_window_every_unapplied_match_is_listed_best_first(env):
    assert env() == ["D", "E", "B", "F"]


def test_the_default_window_of_seven_days_applies_when_the_config_names_none(env):
    """T02: no `max_posted_age_days` in config.json means 7 days: the 40- and 35-day-old matches drop out."""
    assert env(window=DEFAULT_WINDOW) == ["B", "F"]


def test_it_is_regenerated_every_run_even_when_nothing_new_is_scored(env):
    assert env() == ["D", "E", "B", "F"]
    tracker.mark_job("https://x/D", "interview")             # any application status means "applied"
    assert env() == ["E", "B", "F"]
    per_scan = sorted(p.name for p in Path("output/history").glob("jobs_*.csv"))
    assert per_scan == []                                    # nothing scored, so no per-scan CSV: only the rolling file
    env(new=[_job("H")])
    assert len(list(Path("output/history").glob("jobs_*.csv"))) == 1  # the per-scan files stay


def test_an_empty_result_still_rewrites_the_file(env):
    env()
    for name in "BDEF":
        tracker.mark_job(f"https://x/{name}", "rejected")
    assert env() == []
    assert Path("output/open_matches.csv").read_text(encoding="utf-8").startswith("Score (%),Company,")


def test_age_of_a_stored_posting(tmp_path):
    from job_hunt.prefilter import current_age_days
    today = date(2026, 10, 8)
    assert current_age_days("Posted 5 Days Ago", date(2026, 9, 8), today) == 35
    assert current_age_days("2026-09-01", date(2026, 9, 8), today) == 37
    assert current_age_days("", date(2026, 9, 8), today) is None
